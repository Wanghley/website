/**
 * Renders the hero's pre-rendered assets from the LIVE scene, so the poster
 * and the mobile loop are frame-exact copies of what desktop visitors see.
 *
 *   yarn start            # in one terminal
 *   yarn build-hero-assets  # in another
 *
 * Writes public/hero/bench.{avif,webp}, bench-loop.{mp4,webm}, and updates
 * src/data/benchAsset.js with the projected pad/MCU positions.
 * Needs: playwright (devDependency), cwebp, avifenc, ffmpeg.
 */
const { chromium } = require('playwright');
const { execFileSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'public/hero');
const BASE = process.env.BASE_URL || 'http://localhost:3000';
const POSTER = { w: 1300, h: 900 };
const LOOP = { w: 720, h: 498, fps: 12, seconds: 6 };
const INK = '#121314';
const LOOP_SECONDS = 6;

const smooth = (a, b, x) => { const t = Math.min(1, Math.max(0, (x - a) / (b - a))); return t * t * (3 - 2 * t); };
// keep in sync with proximityAtLoop in src/lib/benchState.js
const proximityAtLoop = (sec) => {
  const x = (((sec % LOOP_SECONDS) + LOOP_SECONDS) % LOOP_SECONDS) / LOOP_SECONDS;
  if (x < 0.1) return 0;
  if (x < 0.45) return smooth(0.1, 0.45, x);
  if (x < 0.75) return 1;
  if (x < 0.95) return 1 - smooth(0.75, 0.95, x);
  return 0;
};

async function open(browser, w, h, transparent) {
  const page = await browser.newPage({ viewport: { width: w, height: h } });
  await page.goto(`${BASE}/__capture`, { waitUntil: 'load' });
  await page.addStyleTag({
    content: `.nav,nav,footer,body::after{display:none!important} html,body{background:${transparent ? 'transparent' : INK}!important} #bench-capture{background:${transparent ? 'transparent' : INK}!important}`,
  });
  await page.waitForFunction(() => window.__benchReady, null, { timeout: 90000 });
  await page.waitForTimeout(5000); // let the GLB and textures land
  return page;
}

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'bench-'));
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });

  // --- poster: energised end state, transparent ---
  const pPage = await open(browser, POSTER.w, POSTER.h, true);
  const still = { p: 1, t: 1.3, draw: 1, drop: 1, fade: 1, lookX: 0, lookY: 0 };
  await pPage.evaluate((s) => window.__bench.set(s), still);
  await pPage.evaluate((s) => window.__bench.set(s), still);
  const meta = await pPage.evaluate(() => {
    const { pad, mcu } = window.__bench.state;
    return { pad: { x: pad.x, y: pad.y }, mcu: { x: mcu.x, y: mcu.y } };
  });
  const png = path.join(tmp, 'poster.png');
  await pPage.screenshot({ path: png, omitBackground: true });
  execFileSync('cwebp', ['-q', '86', '-alpha_q', '90', png, '-o', path.join(OUT, 'bench.webp')], { stdio: 'ignore' });
  execFileSync('avifenc', ['--min', '20', '--max', '36', '--speed', '6', png, path.join(OUT, 'bench.avif')], { stdio: 'ignore' });
  await pPage.close();

  // --- loop: proximity follows proximityAtLoop, opaque ink background ---
  const vPage = await open(browser, LOOP.w, LOOP.h, false);
  const frames = LOOP.fps * LOOP.seconds;
  for (let i = 0; i < frames; i += 1) {
    const sec = i / LOOP.fps;
    const s = { p: proximityAtLoop(sec), t: sec + 1.3, draw: 1, drop: 1, fade: 1, lookX: 0, lookY: 0 };
    await vPage.evaluate((x) => window.__bench.set(x), s);
    await vPage.evaluate((x) => window.__bench.set(x), s);
    await vPage.screenshot({ path: path.join(tmp, `f${String(i).padStart(3, '0')}.png`) });
  }
  await vPage.close();
  await browser.close();

  const input = ['-y', '-framerate', String(LOOP.fps), '-i', path.join(tmp, 'f%03d.png')];
  execFileSync('ffmpeg', [...input, '-c:v', 'libx264', '-crf', '30', '-preset', 'slow', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', '-an', path.join(OUT, 'bench-loop.mp4')], { stdio: 'ignore' });
  execFileSync('ffmpeg', [...input, '-c:v', 'libvpx-vp9', '-crf', '38', '-b:v', '0', '-pix_fmt', 'yuv420p', '-an', path.join(OUT, 'bench-loop.webm')], { stdio: 'ignore' });

  const asset = `// Dimensions and landmark positions of the pre-rendered hero assets
// (public/hero/bench.*). GENERATED by scripts/render-hero-assets.js
// (\`yarn build-hero-assets\`), from the live scene's own projection, so the
// DOM label lands on the MCU in the poster and the loop exactly as it does live.
const BENCH_ASSET = ${JSON.stringify({ base: '/hero/bench', width: POSTER.w, height: POSTER.h, ...meta }, null, 2)};

export default BENCH_ASSET;
`;
  fs.writeFileSync(path.join(ROOT, 'src/data/benchAsset.js'), asset);
  fs.rmSync(tmp, { recursive: true, force: true });
  for (const f of ['bench.avif', 'bench.webp', 'bench-loop.mp4', 'bench-loop.webm']) {
    console.log(f, (fs.statSync(path.join(OUT, f)).size / 1024).toFixed(0), 'KB');
  }
})();
